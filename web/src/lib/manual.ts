export function manualSectionID(topic: string, chapter: string, section: string) {
  return `doc-${topic}-${chapter}-${section}`;
}
export function manualHref(topic: string, chapter: string, section?: string) {
  return `/manual?${new URLSearchParams({ topic, chapter })}${section ? `#${manualSectionID(topic, chapter, section)}` : ""}`;
}
export const manualDocuments = manualTopics.flatMap((topic, ti) => topic.chapters.map((chapter, ci) => ({
  topic, chapter, topicNumber: String(ti + 1), number: `${ti + 1}.${ci + 1}`,
  sections: chapter.sections.map((section, si) => ({ ...section, number: `${ti + 1}.${ci + 1}.${si + 1}`, anchor: manualSectionID(topic.id, chapter.id, section.id) })),
})));
export type ManualDocument = typeof manualDocuments[number];
export function searchManual(query: string) {
  const terms = query.trim().toLocaleLowerCase().split(/\s+/).filter(Boolean);
  return manualDocuments.filter(doc => {
    const content = `${doc.topicNumber} ${doc.topic.title} ${doc.number} ${doc.chapter.title} ${doc.chapter.summary} ${JSON.stringify(doc.sections)}`.toLocaleLowerCase();
    return terms.every(term => {
      if (/^\d+(?:\.\d+)*\.?$/.test(term)) {
        const number = term.replace(/\.$/, "");
        return [doc.number, ...doc.sections.map(section => section.number)].some(value => value === number || value.startsWith(`${number}.`));
      }
      return content.includes(term);
    });
  });
}
